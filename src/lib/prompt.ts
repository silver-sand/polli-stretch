/**
 * The stretchtext generation prompt.
 *
 * One request per chunk. The model returns a strict JSON object with two
 * levels per paragraph: `kernel` (minimum essential meaning) and `context`
 * (next level of detail). The `full` level is never generated — it is the
 * exact original text, restored locally. This keeps factual accuracy 100%
 * (nothing is ever invented) and saves Pollen on every expansion.
 */

import type { RawChunk } from "../types";

export const SCHEMA = `{
  "chunks": [
    {
      "id": "<echo the chunk id>",
      "paragraphs": [
        {
          "id": "<echo the paragraph id>",
          "kernel": "<minimum essential meaning>",
          "context": "<next level of detail>"
        }
      ]
    }
  ]
}`;

export function buildStretchPrompt(chunk: RawChunk): {
  system: string;
  user: string;
} {
  const system = `You are a StretchText compiler. Your job is to produce a strict JSON object that describes how a reader can read a chunk of text at two information levels: a compressed "kernel" and a richer "context".

Rules:
- Return ONLY a single JSON object. No markdown fences, no backticks, no prose before or after the JSON. Do not include any text outside the JSON object.
- The JSON must match this exact shape (keys and nesting must be identical):
${SCHEMA}
- "kernel": the minimum essential meaning. One or two short, natural sentences. It must preserve ALL named entities, numbers, dates, percentages, and qualifications. Do not invent, add, or remove any fact. If the original paragraph is already very short (fewer than 60 words), the kernel should be a faithful one-sentence restatement and the context should be the paragraph itself.
- "context": the next level of detail. Enough to fully reconstruct the argument, reasoning, and supporting detail without re-reading the original. Preserve all important numbers, named entities, and reasoning steps. Do not invent, add, or remove any fact. Do not include the original wording itself — the original text is restored locally.
- The "full" level is NOT generated by you. It is the exact original text, restored locally. Do not include a "full" field.
- Echo the chunk id and every paragraph id exactly as given. Do not reorder, rename, or omit any id. If a paragraph is missing from your response, the caller will fall back to its own text for that paragraph — so include every one.
- If a paragraph is already very short (fewer than 60 words), the kernel should be a faithful one-sentence restatement; the context can be the paragraph itself.
- Be faithful to the author's intended meaning. Do not summarize in a way that changes the meaning, exaggerates, or downplays anything.
- If the paragraph contains a quotation, list, or heading, preserve its semantic content in both levels.
- Do not include any commentary, notes, or explanation outside the JSON object.`;

  const paragraphs = chunk.paragraphs
    .map(
      (p) =>
        `Paragraph id: ${p.id}${p.heading ? `\nHeading: ${p.heading}` : ""}\nText: ${p.text}`,
    )
    .join("\n\n---\n\n");

  const user = `Chunk id: ${chunk.id}

Here are ${chunk.paragraphs.length} paragraphs to transform. Echo the chunk id and every paragraph id exactly.

${paragraphs}

Return the JSON object now.`;

  return { system, user };
}